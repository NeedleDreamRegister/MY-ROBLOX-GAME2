[void]$builder.AppendLine('buildPlot()')
foreach ($definition in $definitions) {
    $source = [System.IO.File]::ReadAllText((Join-Path $projectRoot $definition.File))
    if ($source.Contains(']====]')) { throw 'Source conflicts with installer delimiter' }
    [void]$builder.AppendLine('do')
    [void]$builder.AppendLine(('local parent = {0}' -f $definition.Parent))
    [void]$builder.AppendLine(('local item = parent:FindFirstChild("{0}")' -f $definition.Name))
    [void]$builder.AppendLine(('if not item then item = Instance.new("{0}") item.Name = "{1}" item.Parent = parent end' -f $definition.Class,$definition.Name))
    [void]$builder.AppendLine(('assert(item:IsA("{0}"), "Unexpected script class")' -f $definition.Class))
    [void]$builder.AppendLine('item.Source = [====[')
    [void]$builder.AppendLine($source)
    [void]$builder.AppendLine(']====]')
    [void]$builder.AppendLine('end')
}
[void]$builder.AppendLine('game.ServerScriptService.SandPrototype:SetAttribute("PersistenceEnabled", true)')
[void]$builder.AppendLine('game.ServerScriptService.SandPrototype:SetAttribute("PersonalPlotsEnabled", true)')
[void]$builder.AppendLine('workspace:SetAttribute("PersonalPlotsEnabled", true)')
[void]$builder.AppendLine('return "Installed fifteen scripts with cooperative digging and first find"')
$outputDirectory = Join-Path $projectRoot 'generated'
[void][System.IO.Directory]::CreateDirectory($outputDirectory)
$outputPath = Join-Path $outputDirectory 'InstallPersistence.luau'
[System.IO.File]::WriteAllText($outputPath,$builder.ToString(),[System.Text.UTF8Encoding]::new($false))
