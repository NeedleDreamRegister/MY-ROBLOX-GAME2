$builder = [System.Text.StringBuilder]::new()
[void]$builder.AppendLine('-- GENERATED by tools/BuildRecoveryInstaller.ps1; edit src files instead.')
[void]$builder.AppendLine('assert(not game:GetService("RunService"):IsRunning(), "Run only in Edit")')
[void]$builder.AppendLine('assert(workspace:FindFirstChild("SandPrototype") and workspace:FindFirstChild("SandPrototypeStation"), "Open the prototype scene first")')
[void]$builder.AppendLine('local function buildShovel()')
[void]$builder.AppendLine([System.IO.File]::ReadAllText((Join-Path $projectRoot 'tools/BuildTestShovel.luau')))
[void]$builder.AppendLine('end')
[void]$builder.AppendLine('buildShovel()')
[void]$builder.AppendLine('local function buildPath()')
[void]$builder.AppendLine([System.IO.File]::ReadAllText((Join-Path $projectRoot 'tools/BuildPrototypePath.luau')))
[void]$builder.AppendLine('end')
